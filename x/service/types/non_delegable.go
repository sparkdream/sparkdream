package types

// non_delegable.go lists the msg type URLs that MUST NOT be delegable
// via x/authz `MsgExec` or x/session `MsgExecSession`. See
// x-service-spec.md §5.1 + §6.5. The rationale: SPARK-bond commitment
// (MsgRegisterOperator) and significant lifecycle decisions
// (MsgUnbondOperator) are operator-foundational acts; allowing a
// session or authz key to bind someone else's SPARK to obligations
// they didn't personally accept would break the accountability model.
//
// Enforcement is APP-LAYER, not msg-server-layer:
//
//  1. x/authz: include these in the app's authz `ForbiddenMessages`
//     configuration so `MsgExec`-wrapped versions are rejected at the
//     ante handler. See cosmos-sdk's x/authz module setup.
//
//  2. x/session: the chain's x/session params SHOULD exclude these
//     from the active `allowed_msg_types` list (and SHOULD never be
//     re-included by governance proposal). The hardcoded
//     `max_allowed_msg_types` ceiling at genesis is the load-bearing
//     guarantee — see x-session-spec.md.
//
// The TypeURL constants here are the canonical proto type URLs as
// generated by the SDK's MsgServiceDesc. Use these (not string
// literals) when wiring app-level configuration so a proto rename
// surfaces as a compile error.
//
// NOTE: this is a documented-and-exported constant list rather than a
// runtime check inside the msg-server. The reason is structural: by
// the time an authz-`MsgExec`-wrapped MsgRegisterOperator reaches our
// handler, the SDK's authz dispatch has already re-routed the message
// as-if-from-the-granter — both msg.Creator and the apparent signer
// look identical from the handler's perspective. The only reliable
// distinction lives at the ante layer.
var NonDelegableMsgTypeURLs = []string{
	"/sparkdream.service.v1.MsgRegisterOperator",
	"/sparkdream.service.v1.MsgUnbondOperator",
}
