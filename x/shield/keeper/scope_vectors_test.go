var updateScopeVectors = flag.Bool("update-scope-vectors", false, "rewrite testdata/scope_vectors.json")

// scopeVectorsPath is read by web clients' tests (sparkdream-ui) as well:
// they must derive these exact scopes, or every proof they make for that op
// fails at broadcast as "ZK proof verification failed".
const scopeVectorsPath = "testdata/scope_vectors.json"

// scopeVector is one op's registration (shaped like the ShieldedOps query
// response, so a client can pass it straight to its scope code), an inner
// message's scope fields and the shield epoch, and the raw nullifier scope
// the chain binds the proof to.
type scopeVector struct {
	MessageTypeURL     string            `json:"message_type_url"`
	NullifierDomain    uint32            `json:"nullifier_domain"`
	NullifierScopeType string            `json:"nullifier_scope_type"`
	ScopeFieldPath     string            `json:"scope_field_path"`
	EpochWindow        string            `json:"epoch_window"`
	Epoch              string            `json:"epoch"`
	Fields             map[string]string `json:"fields"`
	Scope              string            `json:"scope"`
}

type scopeVectorFile struct {
	Comment string        `json:"comment"`
	Vectors []scopeVector `json:"vectors"`
}

// TestScopeVectors pins the raw nullifier scope of every default consume-mode
// operation, computed by the chain's own resolveNullifierScope over real inner
// messages. A change to the scope rules or the default ops fails here until
// the vectors are regenerated (go test ./x/shield/keeper -run TestScopeVectors
// -update-scope-vectors), and the clients' tests then fail until they match.
func TestScopeVectors(t *testing.T) {
	registry := codectypes.NewInterfaceRegistry()
	for _, register := range []func(codectypes.InterfaceRegistry){
		blogtypes.RegisterInterfaces,
		collecttypes.RegisterInterfaces,
		commonstypes.RegisterInterfaces,
		federationtypes.RegisterInterfaces,
		forumtypes.RegisterInterfaces,
		reptypes.RegisterInterfaces,
		types.RegisterInterfaces,
	} {
		register(registry)
	}
	f := fixtureWithCodec(t, codec.NewProtoCodec(registry))

	var vectors []scopeVector
	for _, reg := range types.DefaultGenesis().RegisteredOps {
		if reg.NullifierMode == types.NullifierMode_NULLIFIER_MODE_OWNERSHIP {
			continue // bound to the content's owner claim, not a resolved scope
		}
		for _, c := range scopeCases(reg) {
			msg, err := registry.Resolve(reg.MessageTypeUrl)
			require.NoError(t, err, reg.MessageTypeUrl)
			for name, value := range c.fields {
				setProtoField(t, msg, name, value)
			}
			inner, err := codectypes.NewAnyWithValue(msg)
			require.NoError(t, err)
			require.NoError(t, f.keeper.SetShieldEpochStateVal(f.ctx, types.ShieldEpochState{CurrentEpoch: c.epoch}))
			scope, err := f.keeper.ResolveNullifierScope(f.ctx, reg, &types.MsgShieldedExec{
				InnerMessage: &any.Any{TypeUrl: inner.TypeUrl, Value: inner.Value},
			})
			require.NoError(t, err, "%s %v", reg.MessageTypeUrl, c.fields)

			fields := map[string]string{}
			for name, value := range c.fields {
				fields[name] = strconv.FormatUint(value, 10)
			}
			vectors = append(vectors, scopeVector{
				MessageTypeURL:     reg.MessageTypeUrl,
				NullifierDomain:    reg.NullifierDomain,
				NullifierScopeType: reg.NullifierScopeType.String(),
				ScopeFieldPath:     reg.ScopeFieldPath,
				EpochWindow:        strconv.FormatUint(reg.EpochWindow, 10),
				Epoch:              strconv.FormatUint(c.epoch, 10),
				Fields:             fields,
				Scope:              strconv.FormatUint(scope, 10),
			})
		}
	}
	require.NotEmpty(t, vectors)

	got, err := json.MarshalIndent(scopeVectorFile{
		Comment: "Generated by TestScopeVectors (x/shield/keeper/scope_vectors_test.go); do not edit. " +
			"The raw nullifier scope the chain binds each default operation's proof to.",
		Vectors: vectors,
	}, "", "  ")
	require.NoError(t, err)
	got = append(got, '\n')

	if *updateScopeVectors {
		require.NoError(t, os.MkdirAll(filepath.Dir(scopeVectorsPath), 0o755))
		require.NoError(t, os.WriteFile(scopeVectorsPath, got, 0o644))
		return
	}
	want, err := os.ReadFile(scopeVectorsPath)
	require.NoError(t, err, "run with -update-scope-vectors to create it")
	require.True(t, bytes.Equal(want, got),
		"%s is stale: the chain's scopes changed. Regenerate it with -update-scope-vectors, then update the web clients' scope code until their tests pass.",
		scopeVectorsPath)
}

type scopeCase struct {
	epoch  uint64
	fields map[string]uint64
}

// scopeCases picks inputs that tell the scope rules apart: epochs on both
// sides of a window boundary, and field values at the packing limits.
func scopeCases(reg types.ShieldedOpRegistration) []scopeCase {
	const epoch = 5
	path := reg.ScopeFieldPath
	switch reg.NullifierScopeType {
	case types.NullifierScopeType_NULLIFIER_SCOPE_EPOCH:
		w := reg.Window()
		var cases []scopeCase
		for _, e := range []uint64{0, 1, w - 1, w, w + 1, 2*w + 1, 1_000_003} {
			cases = append(cases, scopeCase{epoch: e})
		}
		return cases
	case types.NullifierScopeType_NULLIFIER_SCOPE_MESSAGE_FIELD:
		if first, second, ok := strings.Cut(path, types.ScopeFieldFallback); ok {
			return []scopeCase{
				{epoch, map[string]uint64{first: 0, second: 9}},
				{epoch, map[string]uint64{first: 5, second: 9}},
				{epoch, map[string]uint64{first: 1 << 40, second: 0}},
			}
		}
		if qualifier, id, ok := strings.Cut(path, types.ScopeFieldSeparator); ok {
			return []scopeCase{
				{epoch, map[string]uint64{qualifier: 0, id: 7}},
				{epoch, map[string]uint64{qualifier: 1, id: 7}},
				{epoch, map[string]uint64{qualifier: 3, id: 1<<56 - 1}},
			}
		}
		return []scopeCase{
			{epoch, map[string]uint64{path: 1}},
			{epoch, map[string]uint64{path: 42}},
			{epoch, map[string]uint64{path: 1 << 40}},
		}
	default:
		return []scopeCase{{epoch: epoch}, {epoch: 1_000_003}}
	}
}

// setProtoField sets the integer field with protobuf name `name` on msg.
func setProtoField(t *testing.T, msg proto.Message, name string, value uint64) {
	t.Helper()
	rv := reflect.ValueOf(msg).Elem()
	rt := rv.Type()
	for i := 0; i < rt.NumField(); i++ {
		if !strings.Contains(rt.Field(i).Tag.Get("protobuf"), ",name="+name+",") {
			continue
		}
		fv := rv.Field(i)
		switch fv.Kind() {
		case reflect.Uint64, reflect.Uint32:
			fv.SetUint(value)
		case reflect.Int64, reflect.Int32:
			fv.SetInt(int64(value))
		default:
			t.Fatalf("%T.%s is a %s, not an integer scope field", msg, name, fv.Kind())
		}
		return
	}
	t.Fatalf("%T has no field %q", msg, name)
}

// fixtureWithCodec is initFixture with a codec that can unpack other modules'
// messages, so MESSAGE_FIELD scopes are read from the real inner messages.
func fixtureWithCodec(t *testing.T, cdc codec.Codec) *fixture {
	t.Helper()
	key := storetypes.NewKVStoreKey(types.StoreKey)
	testCtx := testutil.DefaultContextWithDB(t, key, storetypes.NewTransientStoreKey("transient_scope_vectors"))
	addrCodec := addresscodec.NewBech32Codec("sprkdrm")
	k := keeper.NewKeeper(
		runtime.NewKVStoreService(key),
		cdc,
		addrCodec,
		authtypes.NewModuleAddress("gov"),
		mockAccountKeeper{},
		mockBankKeeper{},
	)
	k.SetStakingKeeper(mockStakingKeeper{validators: []stakingtypes.Validator{
		{OperatorAddress: "sprkdrmvaloper1aaaaa"},
		{OperatorAddress: "sprkdrmvaloper1bbbbb"},
		{OperatorAddress: "sprkdrmvaloper1ccccc"},
		{OperatorAddress: "sprkdrmvaloper1ddddd"},
		{OperatorAddress: "sprkdrmvaloper1eeeee"},
	}})
	k.SetIdentityKeeper(&mockIdentityKeeperShield{})
	require.NoError(t, k.InitGenesis(testCtx.Ctx, *types.DefaultGenesis()))
	return &fixture{ctx: testCtx.Ctx, keeper: k, addressCodec: addrCodec}
}
